/**
 * Billing: invoices, line items, payments and insurance claims.
 *
 * GET   /api/billing/invoices                 list
 * POST  /api/billing/invoices                 create (optionally from a visit)
 * GET   /api/billing/invoices/:id             invoice with items and payments
 * PATCH /api/billing/invoices/:id             edit a draft
 * POST  /api/billing/invoices/:id/items       add a charge
 * DELETE /api/billing/invoices/:id/items/:itemId
 * POST  /api/billing/invoices/:id/issue       draft -> issued
 * POST  /api/billing/invoices/:id/payments    record a payment
 * POST  /api/billing/invoices/:id/claim       submit / update an insurance claim
 * POST  /api/billing/invoices/:id/void        void an invoice
 * GET   /api/billing/summary                  revenue figures for the dashboard
 *
 * Totals are always recomputed from the line items rather than trusted from the
 * client, and the payment trigger in schema.sql keeps amount_paid/balance_due
 * correct no matter which client records the money.
 */
