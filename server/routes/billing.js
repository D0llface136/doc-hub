router.post(
  '/invoices/:id/payments',
  requirePermission('billing:write'),
  validate(
    z.object({
      amount: money.refine((v) => v > 0, 'Amount must be greater than zero'),
      method: z.enum(['cash', 'card', 'linden', 'insurance', 'bank_transfer', 'waived', 'other']).default('cash'),
      reference: z.string().max(120).optional().nullable(),
      notes: z.string().max(1000).optional().nullable(),
    })
  ),
  asyncHandler(async (req, res) => {
    const id = requireUuid(req.params.id, 'invoice id');
    const b = req.body;

    const invoice = await one('SELECT * FROM invoices WHERE id = $1 AND deleted_at IS NULL', [id]);
    if (!invoice) throw notFound('Invoice');
    if (['void', 'written_off'].includes(invoice.status)) throw badRequest(`A ${invoice.status} invoice cannot take payments.`);
    if (invoice.status === 'draft') throw badRequest('Issue the invoice before recording a payment.');

    // Overpayment is almost always a typo; refuse rather than silently
    // producing a negative balance.
    if (b.amount > Number(invoice.balance_due) + 0.001) {
      throw badRequest(`That is more than the outstanding balance of ${invoice.balance_due}.`);
    }

    const payment = await one(
      `INSERT INTO payments (invoice_id, patient_id, amount, method, reference, notes, received_by)
       VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *`,
      [id, invoice.patient_id, b.amount, b.method, b.reference ?? null, b.notes ?? null, req.staff.id]
    );

    // The AFTER trigger on payments has already updated the invoice.
    const refreshed = await one('SELECT * FROM invoices WHERE id = $1', [id]);

    await audit({
      req, action: 'payment', entityType: 'invoices', entityId: id,
      description: `Recorded ${b.amount} (${b.method}) against ${invoice.invoice_number}; balance now ${refreshed.balance_due}`,
    });

    return created(res, { payment, invoice: refreshed });
  })
);

router.post(
  '/invoices/:id/claim',
  requirePermission('billing:write'),
  validate(
    z.object({
      claim_status: z.enum(['submitted', 'approved', 'denied', 'partially_approved']).default('submitted'),
      claim_reference: z.string().max(120).optional().nullable(),
      claim_notes: z.string().max(2000).optional().nullable(),
      /** Amount the insurer agreed to pay, for approved/partial outcomes. */
      approved_amount: money.optional(),
    })
  ),
  asyncHandler(async (req, res) => {
    const id = requireUuid(req.params.id, 'invoice id');
    const b = req.body;

    const invoice = await one('SELECT * FROM invoices WHERE id = $1 AND deleted_at IS NULL', [id]);
    if (!invoice) throw notFound('Invoice');
    if (invoice.billing_type === 'self_pay') throw badRequest('This is a self-pay invoice; there is nothing to claim.');
    if (!invoice.patient_insurance_id) throw badRequest('No insurance policy is attached to this invoice.');

    const updated = await transaction(async (client) => {
      await client.query(
        `UPDATE invoices SET
           claim_status       = $2,
           claim_reference    = COALESCE($3, claim_reference),
           claim_notes        = COALESCE($4, claim_notes),
           claim_submitted_at = COALESCE(claim_submitted_at, now())
         WHERE id = $1`,
        [id, b.claim_status, b.claim_reference ?? null, b.claim_notes ?? null]
      );

      // An approved claim pays out; record it as a payment so the ledger and
      // the balance both reflect reality.
      if (['approved', 'partially_approved'].includes(b.claim_status)) {
        const amount = b.approved_amount ?? Number(invoice.insurance_covered);
        if (amount > 0) {
          const { rows: already } = await client.query(
            "SELECT 1 FROM payments WHERE invoice_id = $1 AND method = 'insurance' LIMIT 1",
            [id]
          );
          if (already.length === 0) {
            await client.query(
              `INSERT INTO payments (invoice_id, patient_id, amount, method, reference, notes, received_by)
               VALUES ($1,$2,$3,'insurance',$4,'Insurance claim settlement',$5)`,
              [id, invoice.patient_id, Math.min(amount, Number(invoice.balance_due)), b.claim_reference ?? null, req.staff.id]
            );
          }
        }
      }

      const { rows: r } = await client.query('SELECT * FROM invoices WHERE id = $1', [id]);
      return r[0];
    });

    await audit({
      req, action: 'claim', entityType: 'invoices', entityId: id,
      description: `Insurance claim ${b.claim_status} for ${invoice.invoice_number}`,
    });

    return ok(res, updated);
  })
);

router.post(
  '/invoices/:id/void',
  requirePermission('billing:write'),
  validate(z.object({ reason: text(500, 'Reason') })),
  asyncHandler(async (req, res) => {
    const id = requireUuid(req.params.id, 'invoice id');

    const voided = await one(
      `UPDATE invoices
          SET status = 'void', claim_notes = COALESCE(claim_notes || E'\\n', '') || 'Voided: ' || $2
        WHERE id = $1 AND deleted_at IS NULL AND amount_paid = 0 AND status <> 'void'
        RETURNING *`,
      [id, req.body.reason]
    );
    if (!voided) throw badRequest('Only an unpaid, non-void invoice can be voided.');

    await audit({ req, action: 'void', entityType: 'invoices', entityId: id, description: `Voided ${voided.invoice_number}: ${req.body.reason}` });
    return ok(res, voided);
  })
);

