const INVOICE_SELECT = `
  SELECT i.*,
         pt.mrn, pt.first_name, pt.last_name,
         pt.first_name || ' ' || pt.last_name AS patient_name,
         v.visit_number,
         pi.policy_number, pi.provider_name AS insurance_provider,
         pi.verification_status AS insurance_status,
         creator.full_name AS created_by_name
    FROM invoices i
    JOIN patients pt ON pt.id = i.patient_id
    LEFT JOIN patient_visits v ON v.id = i.visit_id
    LEFT JOIN patient_insurance pi ON pi.id = i.patient_insurance_id
    LEFT JOIN staff creator ON creator.id = i.created_by
`;

/**
 * Recompute an invoice's money columns from its line items and insurance.
 * Runs inside the caller's transaction so an invoice is never briefly wrong.
 */
async function recalculateInvoice(client, invoiceId) {
  const { rows: totals } = await client.query(
    'SELECT COALESCE(sum(line_total), 0) AS subtotal FROM invoice_items WHERE invoice_id = $1',
    [invoiceId]
  );
  const subtotal = Number(totals[0].subtotal);

  const { rows: invoiceRows } = await client.query(
    `SELECT i.*, pi.coverage_percent, pi.copay_amount, pi.verification_status,
            ip.default_coverage, ip.default_copay
       FROM invoices i
       LEFT JOIN patient_insurance pi ON pi.id = i.patient_insurance_id
       LEFT JOIN insurance_providers ip ON ip.id = pi.provider_id
      WHERE i.id = $1`,
    [invoiceId]
  );
  const invoice = invoiceRows[0];

  const discount = Number(invoice.discount_amount ?? 0);
  const tax = Number(invoice.tax_amount ?? 0);
  const billable = Math.max(subtotal - discount, 0);

  let insuranceCovered = 0;
  let copay = 0;

  // Only a verified policy actually pays. Anything else bills the patient in
  // full, which is what a clinic would do while a claim is unconfirmed.
  if (invoice.billing_type !== 'self_pay' && invoice.verification_status === 'verified') {
    const coverage = Number(invoice.coverage_percent ?? invoice.default_coverage ?? 0);
    copay = Number(invoice.copay_amount ?? invoice.default_copay ?? 0);
    insuranceCovered = Math.min(billable * coverage, billable);
  }

  const total = Math.round((billable + tax) * 100) / 100;
  const patientResponsibility = Math.round(Math.max(total - insuranceCovered + copay, 0) * 100) / 100;

  const { rows: updated } = await client.query(
    `UPDATE invoices SET
       subtotal               = $2,
       insurance_covered      = $3,
       patient_responsibility = $4,
       total                  = $5,
       balance_due            = GREATEST($5 - amount_paid, 0)
     WHERE id = $1 RETURNING *`,
    [invoiceId, subtotal, Math.round(insuranceCovered * 100) / 100, patientResponsibility, total]
  );

  return updated[0];
}

/**
 * Gather every billable item generated by a visit: the consultation fee, each
 * dispensed medication, each completed lab and imaging order, and any surgery.
 */
async function collectVisitCharges(client, visitId) {
  const items = [];

  const { rows: settings } = await client.query(
    "SELECT key, value FROM clinic_settings WHERE key IN ('billing.visit_fee','billing.emergency_fee')"
  );
  const settingMap = Object.fromEntries(settings.map((s) => [s.key, Number(s.value)]));

  const { rows: visitRows } = await client.query(
    'SELECT visit_type, visit_number FROM patient_visits WHERE id = $1',
    [visitId]
  );
  if (visitRows.length === 0) throw notFound('Visit');
  const visit = visitRows[0];

  const visitFee =
    visit.visit_type === 'emergency'
      ? settingMap['billing.emergency_fee'] ?? 500
      : settingMap['billing.visit_fee'] ?? 150;

  items.push({
    item_type: 'visit',
    source_id: visitId,
    description: `${visit.visit_type.replace('_', ' ')} consultation (${visit.visit_number})`,
    quantity: 1,
    unit_price: visitFee,
  });

  const { rows: meds } = await client.query(
    `SELECT rx.id, rx.medication_name, rx.quantity, COALESCE(m.unit_cost, 0) AS unit_cost
       FROM prescriptions rx
       LEFT JOIN medications m ON m.id = rx.medication_id
       LEFT JOIN pharmacy_queue pq ON pq.prescription_id = rx.id
      WHERE rx.visit_id = $1 AND rx.deleted_at IS NULL
        AND (pq.status IN ('picked_up','ready') OR rx.status IN ('dispensed','filled'))`,
    [visitId]
  );
  for (const med of meds) {
    if (Number(med.unit_cost) <= 0) continue;
    items.push({
      item_type: 'medication',
      source_id: med.id,
      description: med.medication_name,
      quantity: med.quantity,
      unit_price: Number(med.unit_cost),
    });
  }

  const { rows: labs } = await client.query(
    `SELECT lo.id, lo.test_name, COALESCE(cat.cost, 0) AS cost
       FROM laboratory_orders lo
       LEFT JOIN lab_test_catalog cat ON cat.id = lo.test_id
      WHERE lo.visit_id = $1 AND lo.deleted_at IS NULL AND lo.status = 'completed'`,
    [visitId]
  );
  for (const lab of labs) {
    if (Number(lab.cost) <= 0) continue;
    items.push({
      item_type: 'laboratory',
      source_id: lab.id,
      description: `Laboratory: ${lab.test_name}`,
      quantity: 1,
      unit_price: Number(lab.cost),
    });
  }

  const { rows: imaging } = await client.query(
    `SELECT ro.id, ro.study_name, ro.modality, COALESCE(cat.cost, 0) AS cost
       FROM radiology_orders ro
       LEFT JOIN lab_test_catalog cat ON cat.id = ro.test_id
      WHERE ro.visit_id = $1 AND ro.deleted_at IS NULL AND ro.status = 'completed'`,
    [visitId]
  );
  for (const study of imaging) {
    if (Number(study.cost) <= 0) continue;
    items.push({
      item_type: 'radiology',
      source_id: study.id,
      description: `${study.modality.toUpperCase()}: ${study.study_name}`,
      quantity: 1,
      unit_price: Number(study.cost),
    });
  }

  const { rows: surgeries } = await client.query(
    `SELECT id, procedure_name, cost FROM surgeries
      WHERE visit_id = $1 AND deleted_at IS NULL AND status = 'completed' AND cost > 0`,
    [visitId]
  );
  for (const surgery of surgeries) {
    items.push({
      item_type: 'surgery',
      source_id: surgery.id,
      description: `Surgery: ${surgery.procedure_name}`,
      quantity: 1,
      unit_price: Number(surgery.cost),
    });
  }

  return items;
}

