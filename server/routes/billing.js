router.get(
  '/summary',
  requirePermission('billing:read'),
  validate(z.object({ days: z.coerce.number().int().min(1).max(365).optional() }), 'query'),
  asyncHandler(async (req, res) => {
    const days = req.validatedQuery.days ?? 30;

    const [today, period, outstanding, byMethod] = await Promise.all([
      one(
        `SELECT COALESCE(sum(amount), 0) AS revenue, count(*)::int AS payments
           FROM payments WHERE paid_at::date = CURRENT_DATE`
      ),
      one(
        `SELECT COALESCE(sum(amount), 0) AS revenue, count(*)::int AS payments
           FROM payments WHERE paid_at >= now() - ($1 || ' days')::interval`,
        [String(days)]
      ),
      one(
        `SELECT COALESCE(sum(balance_due), 0) AS outstanding,
                count(*) FILTER (WHERE status IN ('issued','partially_paid'))::int AS open_invoices,
                count(*) FILTER (WHERE status = 'overdue' OR (due_date < CURRENT_DATE AND balance_due > 0))::int AS overdue
           FROM invoices WHERE deleted_at IS NULL AND status NOT IN ('void','written_off','draft')`
      ),
      rows(
        `SELECT method, COALESCE(sum(amount), 0) AS total, count(*)::int AS count
           FROM payments WHERE paid_at >= now() - ($1 || ' days')::interval
          GROUP BY method ORDER BY total DESC`,
        [String(days)]
      ),
    ]);

    const daily = await rows(
      `SELECT paid_at::date AS date, COALESCE(sum(amount), 0) AS revenue
         FROM payments WHERE paid_at >= now() - ($1 || ' days')::interval
        GROUP BY paid_at::date ORDER BY date`,
      [String(days)]
    );

    return ok(res, { today, period: { ...period, days }, outstanding, by_method: byMethod, daily });
  })
);

